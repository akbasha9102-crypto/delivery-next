#!/usr/bin/env bash
# تشغيل العملاء الثلاثة بالترتيب
set -e
cd "$(dirname "$0")/.."

echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║          تشغيل العملاء الثلاثة — اختبار عزل المطاعم         ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""

run_agent() {
  local num="$1"
  local file="$2"
  echo "──────────────────────────────────────────"
  echo "▶ تشغيل العميل ${num}..."
  echo "──────────────────────────────────────────"
  npx tsx --env-file=.env.local "scripts/${file}"
  echo ""
}

run_agent "الأول"  "agent1-super-admin-isolation.ts"
run_agent "الثاني" "agent2-dashboard-tenant.ts"
run_agent "الثالث" "agent3-menu-link.ts"

echo "╔══════════════════════════════════════════════════════════════╗"
echo "║           ✅ اجتازت جميع العملاء الثلاثة بنجاح             ║"
echo "╚══════════════════════════════════════════════════════════════╝"
